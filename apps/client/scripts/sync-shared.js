#!/usr/bin/env node
'use strict';
/**
 * Copies the parts of <repo>/shared that the client needs into src/shared so the
 * packaged app is self-contained. Runs before start/build.
 */
const fs = require('fs');
const path = require('path');
const appDir = path.resolve(__dirname, '..');
const repoShared = path.resolve(appDir, '..', '..', 'shared');
const dest = path.join(appDir, 'src', 'shared');
const COPY = [
  'configuration/defaults.js', 'configuration/domains.js', 'configuration/trust.json',
  'utilities/schema.js', 'utilities/css-sanitize.js', 'utilities/markdown.js', 'utilities/signing.js',
  'design/base.css', 'design/icons.js', 'design/brand/icon-client.png', 'design/brand/icon-client.svg', 'design/brand/mark.svg', 'design/fonts',
];
function copy(src, dst) {
  if (fs.statSync(src).isDirectory()) { fs.mkdirSync(dst, { recursive: true }); for (const f of fs.readdirSync(src)) copy(path.join(src, f), path.join(dst, f)); }
  else { fs.mkdirSync(path.dirname(dst), { recursive: true }); fs.copyFileSync(src, dst); }
}
if (!fs.existsSync(repoShared)) {
  if (fs.existsSync(dest)) { console.log('[sync-shared] repo shared/ not found, keeping src/shared'); process.exit(0); }
  console.error('[sync-shared] shared/ missing'); process.exit(1);
}
fs.rmSync(dest, { recursive: true, force: true });
for (const rel of COPY) copy(path.join(repoShared, rel), path.join(dest, rel));
fs.mkdirSync(path.join(appDir, 'build'), { recursive: true });
fs.copyFileSync(path.join(repoShared, 'design/brand/icon-client.png'), path.join(appDir, 'build', 'icon.png'));
fs.writeFileSync(path.join(dest, 'README.txt'), 'Generated by scripts/sync-shared.js from <repo>/shared. Do not edit here.\n');
// Sandboxed preloads cannot require local files, so the game preload is assembled here.
const gamePreload = ['/* GENERATED by scripts/sync-shared.js — edit src/common/crosshair.js and src/preload/game-overlay.js */',
  fs.readFileSync(path.join(appDir, 'src/common/crosshair.js'), 'utf8').replace(/typeof module === 'object' && module.exports/, 'false'),
  fs.readFileSync(path.join(appDir, 'src/preload/game-overlay.js'), 'utf8')].join('\n');
fs.writeFileSync(path.join(appDir, 'src/preload/game.js'), gamePreload);
console.log(`[sync-shared] copied ${COPY.length} entries into src/shared`);
