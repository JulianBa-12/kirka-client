#!/usr/bin/env node
'use strict';
/**
 * Polaris Community Hub — static build.
 *
 *   node scripts/build.js [--out dist] [--data <dir>] [--base /kirka-client/]
 *
 *  - templates src/partials (head, header, footer) into every src/pages/*.html
 *  - bundles src/css (tokens → base → layout → components) into assets/css/site.css,
 *    page CSS stays separate (assets/css/pages/<name>.css)
 *  - copies src/js → assets/js, shared fonts/brand/base.css/icons.js/markdown.js → assets/
 *  - generates assets/js/defaults.js (website.* + community.settings from shared defaults)
 *  - copies public/ (seed data) → dist/, then overlays --data <dir> (real published data) into dist/data
 *  - writes .nojekyll
 *
 * The header/footer are rendered at build time from the shared defaults so every page is usable
 * without JavaScript; at runtime they are re-rendered from the published website bundle.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const APP = path.resolve(__dirname, '..');
const ROOT = path.resolve(APP, '../..');
const SHARED = path.join(ROOT, 'shared');
const { DEFAULTS } = require(path.join(SHARED, 'configuration/defaults.js'));

const args = process.argv.slice(2);
const arg = (name, fallback) => { const i = args.indexOf(name); return i >= 0 && args[i + 1] ? args[i + 1] : fallback; };
const OUT = path.resolve(APP, arg('--out', 'dist'));
const DATA_OVERRIDE = arg('--data', process.env.POLARIS_HUB_DATA || '');
const BASE = arg('--base', process.env.POLARIS_HUB_BASE || '/kirka-client/');

const read = (p) => fs.readFileSync(p, 'utf8');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const hash = (s) => crypto.createHash('sha256').update(s).digest('hex').slice(0, 10);

function rmrf(p) { fs.rmSync(p, { recursive: true, force: true }); }
function mkdirp(p) { fs.mkdirSync(p, { recursive: true }); }
function copyDir(src, dst, filter = () => true) {
  if (!fs.existsSync(src)) return;
  mkdirp(dst);
  for (const ent of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, ent.name); const d = path.join(dst, ent.name);
    if (!filter(s, ent)) continue;
    if (ent.isDirectory()) copyDir(s, d, filter); else fs.copyFileSync(s, d);
  }
}
function write(p, content) { mkdirp(path.dirname(p)); fs.writeFileSync(p, content); }

// ---------------------------------------------------------------- start
rmrf(OUT); mkdirp(OUT);
const A = path.join(OUT, 'assets');

// shared assets
copyDir(path.join(SHARED, 'design/fonts'), path.join(A, 'fonts'), (s) => /\.(woff2|txt)$/.test(s) || fs.statSync(s).isDirectory());
fs.copyFileSync(path.join(SHARED, 'design/base.css'), path.join(A, 'polaris-base.css'));
mkdirp(path.join(A, 'vendor'));
fs.copyFileSync(path.join(SHARED, 'design/icons.js'), path.join(A, 'vendor/icons.js'));
fs.copyFileSync(path.join(SHARED, 'utilities/markdown.js'), path.join(A, 'vendor/markdown.js'));
mkdirp(path.join(A, 'brand'));
// Only the client brand is published. The Owner app icon never ships on the public site.
for (const f of ['mark.svg', 'icon-client.png', 'icon-client.svg']) fs.copyFileSync(path.join(SHARED, 'design/brand', f), path.join(A, 'brand', f));
const markSvg = read(path.join(SHARED, 'design/brand/mark.svg'));
write(path.join(A, 'brand/favicon.svg'), markSvg.replace(/currentColor/g, '#00D9FF'));

// defaults module (browser)
const WEB_DEFAULTS = {
  'website.site': DEFAULTS['website.site'],
  'website.theme': DEFAULTS['website.theme'],
  'website.css': DEFAULTS['website.css'],
  'community.settings': DEFAULTS['community.settings'],
};
write(path.join(A, 'js/defaults.js'),
  '// Generated by scripts/build.js from shared/configuration/defaults.js — do not edit.\n' +
  `export const DEFAULTS = ${JSON.stringify(WEB_DEFAULTS, null, 1)};\n`);

// js
copyDir(path.join(APP, 'src/js'), path.join(A, 'js'));

// css: bundle the global layers, copy page layers
const CSS_LAYERS = ['tokens.css', 'base.css', 'layout.css', 'components.css'];
const siteCss = CSS_LAYERS.map((f) => `/* ---- ${f} ---- */\n` + read(path.join(APP, 'src/css', f))).join('\n');
write(path.join(A, 'css/site.css'), siteCss);
copyDir(path.join(APP, 'src/css/pages'), path.join(A, 'css/pages'));

// public (seed data, robots, etc.) then real data overlay
copyDir(path.join(APP, 'public'), OUT);
if (DATA_OVERRIDE) {
  const dir = path.resolve(DATA_OVERRIDE);
  if (!fs.existsSync(dir)) { console.error(`--data directory not found: ${dir}`); process.exit(1); }
  copyDir(dir, path.join(OUT, 'data'), (s) => fs.statSync(s).isDirectory() || /\.json$/.test(s));
  console.log(`data overlay: ${dir}`);
}
write(path.join(OUT, '.nojekyll'), '');

// technical documentation from <repo>/docs (rendered on documentation.html)
const DOCS = [
  ['install', 'INSTALL.md', 'Users'], ['release-notes', 'RELEASE_NOTES.md', 'Users'], ['plugins', 'PLUGINS.md', 'Creators'],
  ['architecture', 'ARCHITECTURE.md', 'Developers'], ['api', 'API.md', 'Developers'], ['development', 'DEVELOPMENT.md', 'Developers'],
  ['testing', 'TESTING.md', 'Developers'], ['owner-setup', 'OWNER_SETUP.md', 'Self-hosting'],
];
const docIndex = [];
for (const [id, file, group] of DOCS) {
  const src = path.join(ROOT, 'docs', file);
  if (!fs.existsSync(src)) continue;
  const text = read(src);
  write(path.join(OUT, 'docs', `${id}.md`), text);
  const title = ((/^#\s+(.+)$/m.exec(text) || [])[1] || file).trim();
  docIndex.push({ id, title, group, file, bytes: Buffer.byteLength(text), sha: hash(text) });
}
write(path.join(OUT, 'docs', 'index.json'), JSON.stringify({ generatedAt: new Date().toISOString(), docs: docIndex }, null, 1));

// ---------------------------------------------------------------- templating
const site = DEFAULTS['website.site'];
const partial = (n) => read(path.join(APP, 'src/partials', n));
const HEAD = partial('head.html');
const HEADER = partial('header.html');
const FOOTER = partial('footer.html');

const inlineMark = (cls) => markSvg.replace('<svg ', `<svg class="${cls}" aria-hidden="true" focusable="false" `);

function navHtml(current) {
  return site.navigation.filter((n) => n.visible).map((n) => {
    const here = n.href.replace(/[?#].*$/, '') === `${current}.html`;
    return `<li><a href="${esc(n.href)}"${here ? ' aria-current="page"' : ''}>${esc(n.label)}</a></li>`;
  }).join('\n          ');
}
function footerCols() {
  return site.footer.columns.map((c) => `<div class="site-footer__col"><h2 class="pl-label">${esc(c.title)}</h2><ul>${c.links.map((l) => `<li><a href="${esc(l.href)}">${esc(l.label)}</a></li>`).join('')}</ul></div>`).join('\n      ');
}

const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' https: data: http://127.0.0.1:* http://localhost:*",
  "font-src 'self'",
  "connect-src 'self' https: wss: http://127.0.0.1:* http://localhost:* ws://127.0.0.1:* ws://localhost:*",
  "media-src 'self' https:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-src 'none'",
].join('; ');

// cache-busting query strings
const ver = (rel) => `${rel}?v=${hash(fs.readFileSync(path.join(OUT, rel.split('?')[0])))}`;

const pagesDir = path.join(APP, 'src/pages');
const pages = fs.readdirSync(pagesDir).filter((f) => f.endsWith('.html')).sort();
const built = [];
for (const file of pages) {
  const src = read(path.join(pagesDir, file));
  const m = /^<!--@page\s+([\s\S]*?)-->\s*/.exec(src);
  if (!m) throw new Error(`${file}: missing <!--@page {...} --> header`);
  const meta = JSON.parse(m[1]);
  const id = file.replace(/\.html$/, '');
  const body = src.slice(m[0].length);
  const pageCss = (meta.css || []).map((c) => `<link rel="stylesheet" href="${ver(`assets/css/pages/${c}`)}">`).join('\n  ');
  const pageJs = meta.js ? `<script type="module" src="${ver(`assets/js/pages/${meta.js}`)}"></script>` : '';
  const title = meta.title ? `${meta.title} — ${site.siteName}` : site.siteName;
  const vars = {
    id, title: esc(title), description: esc(meta.description || site.tagline), csp: CSP,
    base: meta.base ? `<base href="${esc(BASE)}">` : '',
    siteCss: ver('assets/css/site.css'), baseCss: ver('assets/polaris-base.css'),
    iconsJs: ver('assets/vendor/icons.js'), markdownJs: ver('assets/vendor/markdown.js'),
    pageCss, pageJs,
    nav: navHtml(meta.nav || id), mark: inlineMark('brand__mark'), siteName: esc(site.siteName),
    tagline: esc(site.tagline), footerCols: footerCols(), footerNote: esc(site.footer.note),
    githubUrl: esc(site.githubUrl || 'https://github.com/JulianBa-12/kirka-client'),
    year: String(new Date().getUTCFullYear()),
    heroEyebrow: esc(site.hero.eyebrow), heroTitle: esc(site.hero.title), heroBody: esc(site.hero.body),
    heroPrimaryLabel: esc(site.hero.primaryCta.label), heroPrimaryHref: esc(site.hero.primaryCta.href),
    heroSecondaryLabel: esc(site.hero.secondaryCta.label), heroSecondaryHref: esc(site.hero.secondaryCta.href),
    bodyClass: meta.bodyClass ? ` class="${esc(meta.bodyClass)}"` : '',
  };
  const fill = (tpl) => tpl.replace(/\{\{(\w+)\}\}/g, (_, k) => { if (!(k in vars)) throw new Error(`${file}: unknown var ${k}`); return vars[k]; });
  const html = fill(HEAD) + fill(HEADER) + `<main id="main" tabindex="-1">\n${fill(body)}\n</main>\n` + fill(FOOTER);
  write(path.join(OUT, file), html);
  built.push(file);
}

console.log(`built ${built.length} pages → ${path.relative(process.cwd(), OUT) || OUT}`);
console.log('  ' + built.join(' '));
